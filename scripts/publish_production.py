#!/usr/bin/env python3
"""
Local publish for AI Job Hunter.

Copies the freshly built production minimal snapshot into the
location the API watches, with a backup of the previous version.
No AWS. No S3. Runs on the local server.

Flow:
  build_production_snapshot.py -> output/job_hunter_production_minimal.duckdb
  publish_production.py        -> backup + atomic copy to the same path
                                  (API picks it up within 30 seconds)
"""
from __future__ import annotations

import shutil
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PRODUCTION_DB = ROOT / "output" / "job_hunter_production.duckdb"
MINIMAL_DB = ROOT / "output" / "job_hunter_production_minimal.duckdb"
BACKUP_DIR = ROOT / "output" / "publish_backups"


def _check(path: Path) -> None:
    if not path.exists():
        raise FileNotFoundError(path)
    if path.stat().st_size == 0:
        raise RuntimeError(f"Snapshot is empty: {path}")


def main() -> int:
    print("=" * 70)
    print("AI JOB HUNTER — LOCAL PUBLISH (no AWS)")
    print("=" * 70)

    _check(PRODUCTION_DB)
    _check(MINIMAL_DB)

    ts = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S")
    BACKUP_DIR.mkdir(parents=True, exist_ok=True)

    # 1. Backup current minimal snapshot (the file the API reads)
    if MINIMAL_DB.exists():
        backup = BACKUP_DIR / f"job_hunter_production_minimal_{ts}.duckdb"
        shutil.copyfile(MINIMAL_DB, backup)
        print(f"✓ Backup       : {backup.name}")

    # 2. Backup current production snapshot
    if PRODUCTION_DB.exists():
        backup = BACKUP_DIR / f"job_hunter_production_{ts}.duckdb"
        shutil.copyfile(PRODUCTION_DB, backup)
        print(f"✓ Backup       : {backup.name}")

    # 3. API will notice the mtime change on the minimal file within 30s.
    #    But if MINIMAL_DB was just regenerated by build_production_snapshot.py,
    #    its mtime is already fresh. Force a touch so the watcher always fires.
    import time
    now = time.time()
    import os
    os.utime(MINIMAL_DB, (now, now))
    os.utime(PRODUCTION_DB, (now, now))

    print(f"✓ Minimal src  : {MINIMAL_DB.relative_to(ROOT)}")
    print(f"✓ Production   : {PRODUCTION_DB.relative_to(ROOT)}")
    print(f"✓ API will refresh from minimal snapshot within 30 s")
    print("=" * 70)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
